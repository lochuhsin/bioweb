export type IconName = keyof typeof ART;

const cache = new Map<IconName, string>();

function rects(name: IconName): string {
  let out = cache.get(name);
  if (out) return out;
  out = '';
  ART[name].forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      const start = x;
      while (row[x] === '#') x++;
      out += `<rect x="${start}" y="${y}" width="${x - start}" height="1"/>`;
    }
  });
  cache.set(name, out);
  return out;
}

export function icon(name: IconName, className = 'icon'): string {
  return `<svg class="${className}" viewBox="0 0 16 16" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${rects(name)}</svg>`;
}
