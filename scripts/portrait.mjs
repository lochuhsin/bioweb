// Turns a background-removed portrait (a PNG with transparency) into the ASCII art on the about page.
// The photo stays on your machine (keep it in private/, which git ignores); only the generated text
// in src/portrait-ascii.ts is published.
//
// usage: npm run portrait -- private/portrait-source.png [columns]
import { readFileSync, writeFileSync } from 'node:fs';
import { PNG } from 'pngjs';

const RAMP = ' .,:;~-=+*#%@';
/** Glyph width divided by line height (0.6em wide glyphs, 1.2 line height). */
const CHAR_ASPECT = 0.5;

const [input, colsArg] = process.argv.slice(2);
if (!input) {
  console.error('usage: npm run portrait -- <photo.png> [columns]');
  process.exit(1);
}
const cols = Number(colsArg) || 110;
const { width, height, data } = PNG.sync.read(readFileSync(input));
const rows = Math.max(1, Math.round(cols * (height / width) * CHAR_ASPECT));

// Average every pixel that falls in a cell, weighted by how much of it the cell covers.
// Color is weighted by alpha, so transparent pixels don't darken the edges.
const luma = new Float32Array(cols * rows);
const alpha = new Float32Array(cols * rows);
const cellW = width / cols;
const cellH = height / rows;
for (let r = 0; r < rows; r++) {
  const y0 = r * cellH;
  const y1 = y0 + cellH;
  for (let c = 0; c < cols; c++) {
    const x0 = c * cellW;
    const x1 = x0 + cellW;
    let area = 0;
    let a = 0;
    let l = 0;
    for (let y = Math.floor(y0); y < Math.min(height, Math.ceil(y1)); y++) {
      const wy = Math.min(y + 1, y1) - Math.max(y, y0);
      for (let x = Math.floor(x0); x < Math.min(width, Math.ceil(x1)); x++) {
        const w = wy * (Math.min(x + 1, x1) - Math.max(x, x0));
        const i = (y * width + x) * 4;
        const pa = data[i + 3] / 255;
        area += w;
        a += w * pa;
        l += (w * pa * (0.2126 * data[i] + 0.7152 * data[i + 1] + 0.0722 * data[i + 2])) / 255;
      }
    }
    const k = r * cols + c;
    alpha[k] = area > 0 ? a / area : 0;
    luma[k] = a > 0 ? l / a : 0;
  }
}

// Same mapping as src/ascii.ts uses for cut-out photos: stretch the subject's brightness range over
// the whole ramp so a face keeps its features, and give the subject a faint minimum density so dark
// hair and clothes keep their outline.
const subject = Array.from(luma)
  .filter((_, i) => alpha[i] > 0.5)
  .sort((p, q) => p - q);
const cutout = alpha.some((v) => v < 0.5);
const floor = cutout ? 0.16 : 0;
let lo = 0;
let hi = 1;
if (cutout && subject.length > 10) {
  lo = subject[Math.floor(subject.length * 0.05)];
  hi = Math.max(lo + 0.05, subject[Math.floor(subject.length * 0.98)]);
}

/** invert: the light theme draws dark ink on a light page, so dark parts of the photo get dense glyphs. */
function render(invert) {
  const lines = [];
  for (let y = 0; y < rows; y++) {
    let line = '';
    for (let x = 0; x < cols; x++) {
      const i = y * cols + x;
      const level = Math.min(1, Math.max(0, (luma[i] - lo) / (hi - lo)));
      const tone = invert ? 1 - level : level;
      let d = alpha[i] * (floor + (1 - floor) * tone);
      d = Math.min(1, Math.max(0, (d - 0.5) * 1.12 + 0.5)) ** 0.95;
      line += RAMP[Math.round(d * (RAMP.length - 1))];
    }
    lines.push(line.trimEnd());
  }
  return lines.join('\n');
}

const art = { cols, rows, dark: render(false), light: render(true) };
const out = `// Generated by scripts/portrait.mjs (npm run portrait). Do not edit by hand.
export const portrait = ${JSON.stringify(art, null, 2)};
`;
writeFileSync(new URL('../src/portrait-ascii.ts', import.meta.url), out);
console.log(`wrote src/portrait-ascii.ts: ${cols} x ${rows} characters`);
